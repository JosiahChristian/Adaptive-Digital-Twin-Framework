from pathlib import Path

import experiments.action_conditioned_support_representation_analysis as source


TARGET_SEEDS = list(
    range(
        44071,
        44111,
    )
)


RESULTS_DIR = Path(
    "results"
)


SUMMARY_OUTPUT_PATH = (
    RESULTS_DIR
    / "action_conditioned_support_representation_analysis_071_110.csv"
)

FOLD_OUTPUT_PATH = (
    RESULTS_DIR
    / "action_conditioned_support_representation_analysis_folds_071_110.csv"
)

ACTION_OUTPUT_PATH = (
    RESULTS_DIR
    / "action_conditioned_support_representation_analysis_actions_071_110.csv"
)

COEFFICIENT_OUTPUT_PATH = (
    RESULTS_DIR
    / "action_conditioned_support_representation_analysis_coefficients_071_110.csv"
)


def main():
    print(
        "=" * 210
    )

    print(
        "ADAPTIVE DIGITAL TWIN - "
        "RICH PRE-ACTION SUPPORT GEOMETRY "
        "RECONSTRUCTION 44071-44110"
    )

    print(
        "=" * 210
    )

    print(
        f"source module="
        f"{source.__name__}"
    )

    print(
        f"target seeds="
        f"{TARGET_SEEDS[0]}-"
        f"{TARGET_SEEDS[-1]}"
    )

    print(
        f"seed count="
        f"{len(TARGET_SEEDS)}"
    )

    print()

    print(
        "REUSING ESTABLISHED ACTION-CONDITIONED "
        "SUPPORT REPRESENTATION IMPLEMENTATION"
    )

    # Change only the historical seed population.
    source.ANALYSIS_SEEDS = list(
        TARGET_SEEDS
    )

    # Redirect every output so the original Experiment results
    # remain untouched.
    source.OUTPUT_PATH = (
        SUMMARY_OUTPUT_PATH
    )

    source.FOLD_OUTPUT_PATH = (
        FOLD_OUTPUT_PATH
    )

    source.ACTION_OUTPUT_PATH = (
        ACTION_OUTPUT_PATH
    )

    source.COEFFICIENT_OUTPUT_PATH = (
        COEFFICIENT_OUTPUT_PATH
    )

    print(
        f"summary output="
        f"{source.OUTPUT_PATH}"
    )

    print(
        f"fold output="
        f"{source.FOLD_OUTPUT_PATH}"
    )

    print(
        f"action output="
        f"{source.ACTION_OUTPUT_PATH}"
    )

    print(
        f"coefficient output="
        f"{source.COEFFICIENT_OUTPUT_PATH}"
    )

    print()

    # This invokes the already-established feature construction,
    # simulation, action-support representation, and output logic.
    #
    # No feature definition is rewritten here.
    source.main()

    print()

    print(
        "RECONSTRUCTION COMPLETE"
    )

    print(
        "The rich pre-action representation was generated by "
        "the existing action-conditioned support implementation "
        "with only ANALYSIS_SEEDS and output destinations changed."
    )

    print(
        "No Experiment 114 regime or harmful-outcome model was "
        "fit during this reconstruction."
    )

    print(
        "=" * 210
    )


if __name__ == "__main__":
    main()